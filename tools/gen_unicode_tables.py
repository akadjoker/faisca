#!/usr/bin/env python3
"""Writes src/unicode_tables.inc from Python's Unicode database.

    python3 tools/gen_unicode_tables.py src/unicode_tables.inc

One byte per code point: bit 0 letter (\\p{L}), bit 1 number (\\p{N}), bit 2
whitespace (\\s). Stored as a two level table: 256 code points per block,
identical blocks shared.
"""

import sys
import unicodedata

LETTER = 1
NUMBER = 2
WHITESPACE = 4

WHITESPACE_CODE_POINTS = [
    0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x20, 0x85, 0xA0, 0x1680,
    0x2000, 0x2001, 0x2002, 0x2003, 0x2004, 0x2005, 0x2006, 0x2007, 0x2008, 0x2009, 0x200A,
    0x2028, 0x2029, 0x202F, 0x205F, 0x3000,
]

CODE_POINTS = 0x110000
BLOCK = 256


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2

    classes = bytearray(CODE_POINTS)
    for code_point in range(CODE_POINTS):
        category = unicodedata.category(chr(code_point))
        if category[0] == "L":
            classes[code_point] |= LETTER
        elif category[0] == "N":
            classes[code_point] |= NUMBER
    for code_point in WHITESPACE_CODE_POINTS:
        classes[code_point] |= WHITESPACE

    blocks = []
    block_of = {}
    index = []
    for start in range(0, CODE_POINTS, BLOCK):
        block = bytes(classes[start:start + BLOCK])
        if block not in block_of:
            block_of[block] = len(blocks)
            blocks.append(block)
        index.append(block_of[block])

    with open(sys.argv[1], "w", encoding="ascii", newline="\n") as out:
        out.write(f"// generated by tools/gen_unicode_tables.py from Unicode {unicodedata.unidata_version}\n\n")
        out.write(f"const uint16_t UNICODE_BLOCK_INDEX[{len(index)}] = {{\n")
        for row in range(0, len(index), 16):
            out.write("    " + ", ".join(str(v) for v in index[row:row + 16]) + ",\n")
        out.write("};\n\n")
        out.write(f"const uint8_t UNICODE_BLOCKS[{len(blocks)}][{BLOCK}] = {{\n")
        for block in blocks:
            out.write("    {\n")
            for row in range(0, BLOCK, 32):
                out.write("        " + ",".join(str(v) for v in block[row:row + 32]) + ",\n")
            out.write("    },\n")
        out.write("};\n")

    print(f"{len(blocks)} blocks, {len(index) * 2 + len(blocks) * BLOCK} bytes of tables")
    return 0


if __name__ == "__main__":
    sys.exit(main())
